"""旁路升格重放（显式回正写闸，口径乙）。

全局唯一架构：**以显式回正写闸为准**。
- 旁路匣行是终态「待回正」，装载路径禁止无入口直接改其刷卡命运；
  只有经回正写闸、校验通过后才能关闭旁路并重放。
- 回正是异常回放链路：旁路行状态、刷卡点命运、开腿账/行程账写入同票事务，
  同成败（异常整票回滚，不留半截开腿/半截行程）。
- 写闸以 BEGIN IMMEDIATE 取库级写锁，并发回正/装载串行化；
  回正审计对旁路编号 UNIQUE，重复回正幂等返回原审计，绝不双行程。

可回正的旁路原因：出站孤儿、缺腿超时、重复进站。
不可回正（终态）：未知站点、方向非法（主数据/契约缺陷，回放仍必败）。
"""
import json

from app.db import 连接
from app.seed import 此刻
from app.services import 时间, 装载

可回正原因 = {"出站孤儿", "缺腿超时", "重复进站"}


class 回正拒绝(Exception):
    """写闸校验未过：整票拒绝、零写入。"""

    def __init__(self, 原因: str, 状态码: int = 409):
        super().__init__(原因)
        self.原因 = 原因
        self.状态码 = 状态码


def _取旁路(conn, 旁路编号: int):
    return conn.execute(
        "SELECT * FROM 旁路匣 WHERE 编号=?", (旁路编号,)
    ).fetchone()


def _校验(conn, 行) -> dict:
    """只读校验：返回重放计划；不可回正则抛 回正拒绝。不做任何写入。"""
    if 行 is None:
        raise 回正拒绝(f"旁路编号不存在", 404)
    if 行["状态"] != "待回正":
        审计 = conn.execute(
            "SELECT * FROM 回正审计 WHERE 旁路编号=?", (行["编号"],)
        ).fetchone()
        raise 回正拒绝(
            f"旁路{行['编号']}已回正（审计{审计['审计编号'] if 审计 else '?'}），禁止重复回正",
            409,
        )
    if 行["原因"] not in 可回正原因:
        raise 回正拒绝(
            f"旁路原因「{行['原因']}」为终态缺陷，不允许回正（需先修主数据/契约）",
            422,
        )

    刷卡 = conn.execute(
        "SELECT * FROM 刷卡点 WHERE 事件编号=?", (行["事件编号"],)
    ).fetchone()
    if not 刷卡:
        raise 回正拒绝("旁路对应刷卡点缺失，无法重放", 422)
    if 刷卡["命运"] != "已旁路":
        raise 回正拒绝(
            f"刷卡点命运已被改为「{刷卡['命运']}」——禁止无写闸改命运，回正拒绝", 409
        )
    卡号, 事件编号 = 刷卡["卡号"], 刷卡["事件编号"]
    方向, 站点键, 事件时 = 刷卡["方向"], 刷卡["站点键"], 刷卡["事件时"]
    在途 = conn.execute(
        "SELECT * FROM 开腿账 WHERE 卡号=? AND 状态='在途' ORDER BY 进站事件时 ASC LIMIT 1",
        (卡号,),
    ).fetchone()

    if 行["原因"] == "出站孤儿":
        if 方向 != "出站":
            raise 回正拒绝("出站孤儿旁路的刷卡点方向非出站", 422)
        if not 在途:
            raise 回正拒绝("同卡仍无在途开腿，孤儿出站无法成对，保持旁路", 422)
        return {"模式": "成对", "开腿": 在途}

    if 行["原因"] == "缺腿超时":
        if 方向 != "进站":
            raise 回正拒绝("缺腿超时旁路的刷卡点方向非进站", 422)
        旧腿 = conn.execute(
            "SELECT * FROM 开腿账 WHERE 进站事件编号=? AND 状态='已旁路'", (事件编号,)
        ).fetchone()
        if not 旧腿:
            raise 回正拒绝("缺腿超时对应的已旁路开腿不存在，无法重新开腿", 422)
        if 在途:
            raise 回正拒绝(
                "同卡存在在途开腿，重开旧腿会造成双开腿，保持旁路", 409
            )
        return {"模式": "开腿", "旧腿": 旧腿}

    # 重复进站：被旁路的是旧进站
    if 方向 != "进站":
        raise 回正拒绝("重复进站旁路的刷卡点方向非进站", 422)
    if 在途:
        raise 回正拒绝(
            "同卡已有在途开腿，重放旧进站会触发连环重复进站，保持旁路", 409
        )
    旧腿 = conn.execute(
        "SELECT * FROM 开腿账 WHERE 进站事件编号=? AND 状态='已旁路'", (事件编号,)
    ).fetchone()
    if not 旧腿:
        raise 回正拒绝("重复进站对应的已旁路开腿不存在，无法重新开腿", 422)
    return {"模式": "开腿", "旧腿": 旧腿}


def 只读预览(旁路编号: int) -> dict:
    """回正只读接口：旁路编号、是否允许回正、重放结果、审计编号、valid。"""
    conn = 连接()
    try:
        行 = _取旁路(conn, 旁路编号)
        if 行 is None:
            return {
                "旁路编号": 旁路编号,
                "valid": False,
                "是否允许回正": False,
                "原因": "旁路编号不存在",
                "重放结果": None,
                "审计编号": None,
            }
        已审计 = conn.execute(
            "SELECT * FROM 回正审计 WHERE 旁路编号=?", (旁路编号,)
        ).fetchone()
        if 已审计:
            return {
                "旁路编号": 旁路编号,
                "valid": True,
                "是否允许回正": False,
                "原因": f"已回正（审计{已审计['审计编号']}），重复回正幂等返回",
                "重放结果": {
                    "结果": 已审计["结果"],
                    "行程键": 已审计["行程键"],
                    "开腿键": 已审计["开腿键"],
                },
                "审计编号": 已审计["审计编号"],
            }
        try:
            计划 = _校验(conn, 行)
        except 回正拒绝 as e:
            return {
                "旁路编号": 旁路编号,
                "valid": True,
                "是否允许回正": False,
                "原因": e.原因,
                "重放结果": None,
                "审计编号": None,
            }
        return {
            "旁路编号": 旁路编号,
            "valid": True,
            "是否允许回正": True,
            "原因": 行["原因"],
            "重放结果": {
                "模式": 计划["模式"],
                "结果": "成对" if 计划["模式"] == "成对" else "重新开腿",
                "行程键": (
                    f"行-{计划['开腿']['进站事件编号']}-{行['事件编号']}"
                    if 计划["模式"] == "成对"
                    else ""
                ),
                "开腿键": (
                    计划["旧腿"]["开腿键"] if 计划["模式"] == "开腿" else ""
                ),
            },
            "审计编号": None,
        }
    finally:
        conn.close()


def _重放(conn, 行, 刷卡, 计划: dict) -> dict:
    """在调用方事务内执行重放：只动既有刷卡点命运与开腿/行程，不插新刷卡点。"""
    处理时 = 此刻()
    卡号, 事件编号 = 刷卡["卡号"], 刷卡["事件编号"]
    站点键, 事件时 = 刷卡["站点键"], 刷卡["事件时"]

    if 计划["模式"] == "成对":
        r = 装载.出站处理(conn, 卡号, 站点键, 事件编号, 事件时, 处理时)
        if r["命运"] != "已成对":
            raise 回正拒绝("重放出站未成对（在途开腿已被并发改走），整票回滚", 409)
        return {"结果": "成对", "行程键": r["行程键"], "开腿键": ""}

    旧腿 = 计划["旧腿"]
    # 缺腿超时/重复进站：复活已旁路旧开腿，刷卡命运回到已开腿
    cur = conn.execute(
        "UPDATE 开腿账 SET 状态='在途', 更新处理时=? WHERE 开腿键=? AND 状态='已旁路'",
        (处理时, 旧腿["开腿键"]),
    )
    if cur.rowcount == 0:
        raise 回正拒绝("旧开腿已被并发改动，整票回滚", 409)
    conn.execute(
        "UPDATE 刷卡点 SET 命运='已开腿', 行程键='' WHERE 事件编号=? AND 命运='已旁路'",
        (事件编号,),
    )
    return {"结果": "重新开腿", "行程键": "", "开腿键": 旧腿["开腿键"]}


def 回正写闸(旁路编号: int) -> dict:
    """显式回正写闸：校验→关旁路→重放→审计，单票同成败。

    重复回正幂等：返回原审计、零新行程。
    """
    conn = 连接()
    try:
        conn.execute("BEGIN IMMEDIATE")
        行 = _取旁路(conn, 旁路编号)
        if 行 is None:
            conn.rollback()
            raise 回正拒绝("旁路编号不存在", 404)

        旧审计 = conn.execute(
            "SELECT * FROM 回正审计 WHERE 旁路编号=?", (旁路编号,)
        ).fetchone()
        if 旧审计:
            # 幂等：重复回正不重放、不产生新行程
            conn.rollback()
            return {
                "旁路编号": 旁路编号,
                "valid": True,
                "是否允许回正": False,
                "幂等": True,
                "原因": "重复回正已被写闸吞掉，未产生新行程",
                "重放结果": {
                    "结果": 旧审计["结果"],
                    "行程键": 旧审计["行程键"],
                    "开腿键": 旧审计["开腿键"],
                },
                "审计编号": 旧审计["审计编号"],
            }

        计划 = _校验(conn, 行)
        刷卡 = conn.execute(
            "SELECT * FROM 刷卡点 WHERE 事件编号=?", (行["事件编号"],)
        ).fetchone()
        重放 = _重放(conn, 行, 刷卡, 计划)
        审计时刻 = 此刻()
        cur = conn.execute(
            """INSERT INTO 回正审计(旁路编号,卡号,事件编号,结果,行程键,开腿键,时刻)
               VALUES (?,?,?,?,?,?,?)""",
            (
                旁路编号,
                刷卡["卡号"],
                行["事件编号"],
                重放["结果"],
                重放["行程键"],
                重放["开腿键"],
                审计时刻,
            ),
        )
        审计编号 = cur.lastrowid
        conn.execute(
            "UPDATE 旁路匣 SET 状态='已回正', 回正审计编号=? WHERE 编号=? AND 状态='待回正'",
            (审计编号, 旁路编号),
        )
        conn.commit()
        return {
            "旁路编号": 旁路编号,
            "valid": True,
            "是否允许回正": True,
            "幂等": False,
            "原因": 行["原因"],
            "重放结果": 重放,
            "审计编号": 审计编号,
        }
    except 回正拒绝:
        conn.rollback()
        raise
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def 列审计() -> list:
    conn = 连接()
    try:
        return [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 回正审计 ORDER BY 审计编号 DESC LIMIT 100"
            )
        ]
    finally:
        conn.close()
